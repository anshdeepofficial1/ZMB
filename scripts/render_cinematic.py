"""Strict cinematic-footage renderer.

Consumes REAL scene-specific MP4 assets (e.g. generated by a ComfyUI GPU workflow).
Never pretends to generate video on a CPU runner and never silently substitutes
flat procedural footage when a required cinematic shot is absent.
"""
from __future__ import annotations

import hashlib
import json
from fractions import Fraction
from pathlib import Path

from common import OUT_DIR, ROOT, run
from visual_manifest import CINEMATIC_ROOT, build_manifest, VisualContractError


def required_clips(ep: dict, shots: list) -> list[tuple[object, Path]]:
    base = CINEMATIC_ROOT / ep["arc"] / ep["node"]
    paths = []
    line_index = 0
    for shot in shots:
        if shot.kind == "line":
            # Only narration lines require scene-specific AI-generated films.
            # Interactive vote/ending cards are built as honest typography.
            path = base / f"{line_index:02d}.mp4"
            line_index += 1
            paths.append((shot, path))
        elif shot.kind not in {"vote", "ending"}:
            raise VisualContractError(
                f"unsupported non-narrated cinematic timeline card: {shot.kind}"
            )
    return paths


def _probe_video(path: Path) -> dict:
    result = run([
        "ffprobe", "-v", "error", "-show_streams", "-show_format",
        "-of", "json", str(path),
    ])
    info = json.loads(result.stdout)
    streams = info.get("streams") or []
    video_streams = [s for s in streams if s.get("codec_type") == "video"]
    if len(video_streams) != 1:
        raise VisualContractError(f"cinematic clip must have exactly one video stream: {path}")
    stream = video_streams[0]
    width, height = int(stream.get("width") or 0), int(stream.get("height") or 0)
    if width < 720 or height < 1280 or abs(width / height - 9 / 16) > 0.035:
        raise VisualContractError(
            f"cinematic clip must be portrait 9:16 at 720x1280+; "
            f"got {width}x{height} in {path}"
        )
    try:
        fps = float(Fraction(str(stream.get("avg_frame_rate") or "0/1")))
    except (ValueError, ZeroDivisionError) as exc:
        raise VisualContractError(f"cinematic clip has unreadable frame rate: {path}") from exc
    if not 23.5 <= fps <= 120:
        raise VisualContractError(f"cinematic clip frame rate must be 24-120 fps: {fps}")
    try:
        duration = float((info.get("format") or {}).get("duration") or 0)
    except (TypeError, ValueError) as exc:
        raise VisualContractError(f"cinematic clip duration unreadable: {path}") from exc
    if not 0 < duration < 300:
        raise VisualContractError(f"cinematic asset duration invalid: {path}")
    return {"duration": duration, "width": width, "height": height, "fps": fps,
            "streams": streams}


def validate_assets(ep: dict, shots: list) -> list[tuple[object, Path]]:
    selected = required_clips(ep, shots)
    missing = [str(p.relative_to(ROOT)) for _, p in selected if not p.is_file()]
    if missing:
        raise VisualContractError(
            "Missing scene-specific cinematic footage (no fallback allowed):\n"
            + "\n".join(missing)
        )
    hashes = set()
    for shot, path in selected:
        info = _probe_video(path)
        if info["duration"] + 0.03 < shot.dur:
            raise VisualContractError(
                f"shot {path.name} is only {info['duration']:.2f}s, "
                f"but narration/shot needs {shot.dur:.2f}s; "
                "do not hide gaps using a repeating loop."
            )
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        if digest in hashes:
            raise VisualContractError(
                f"duplicate cinematic clip content detected: {path}. "
                "Each spoken action needs original scene-specific footage."
            )
        hashes.add(digest)
    return selected


def _ass_clock(seconds: float) -> str:
    centis = int(round(max(0.0, seconds) * 100.0))
    h, m = divmod(centis, 360000)
    minute, rest = divmod(m, 6000)
    second, hund = divmod(rest, 100)
    return f"{h}:{minute:02d}:{second:02d}.{hund:02d}"


def _ass_escape(text: str) -> str:
    return (text.replace("\\", r"\\")
            .replace("{", "(").replace("}", ")")
            .replace("\n", " "))


def build_subtitles(shots: list, voices: list, path: Path) -> None:
    header = """[Script Info]
ScriptType: v4.00+
PlayResX: 1080
PlayResY: 1920
WrapStyle: 2
ScaledBorderAndShadow: yes

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: ZMB,DejaVu Sans,61,&H00F4F4F0,&H00A9CEF1,&H800B0B12,&H990A111B,-1,0,0,0,100,100,0.4,0,3,9,0,2,96,230,410,1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""
    events = []
    line_shots = [shot for shot in shots if shot.kind == "line"]
    if len(line_shots) != len(voices):
        raise VisualContractError("narration timeline and visual shot count differ")
    for shot, voice in zip(line_shots, voices):
        words = voice.get("words") or []
        if not words:
            raise VisualContractError("missing TTS word timings; captions must align with speech")
        # Edge TTS sometimes strips punctuation from WordBoundary tokens.
        # Restore it only when the narrated source maps 1:1 to speech words.
        from string import punctuation
        source_words = str(voice.get("text", "")).split()
        if len(source_words) == len(words) and all(
            source_words[i].strip(punctuation).casefold()
            == str(word.get("w", "")).strip(punctuation).casefold()
            for i, word in enumerate(words)
        ):
            tokens = source_words
        else:
            tokens = [str(word.get("w", "")) for word in words]
        i = 0
        while i < len(words):
            end_index = i
            current = []
            while end_index < len(words) and len(current) < 4:
                candidate = " ".join(current + [tokens[end_index]])
                if current and len(candidate) > 29:
                    break
                current.append(tokens[end_index])
                end_index += 1
                # Never carry the start of a new sentence into the prior
                # caption. Short complete phrases feel editorial, not karaoke.
                if current[-1].rstrip().endswith((".", "!", "?", "…")):
                    break
            if not current:
                raise VisualContractError("cannot place spoken subtitle in safe caption box")
            phrase = words[i:end_index]
            start = shot.start + float(phrase[0].get("start", 0))
            end = min(shot.end, shot.start + float(phrase[-1].get("end", shot.dur)) + 0.10)
            if end <= start or start >= shot.end:
                raise VisualContractError("TTS timing extends outside narrated scene")
            events.append((start, max(start + 0.12, end), " ".join(current)))
            i = end_index
    for start, end, string in events:
        if len(string) > 39:
            raise VisualContractError("subtitle line too long for phone safe zone")
        header += (
            "Dialogue: 0," + _ass_clock(start) + ","
            + _ass_clock(end) + ",ZMB,,0,0,0,,"
            + r"{\fad(65,100)}" + _ass_escape(string) + "\n"
        )
    path.write_text(header, encoding="utf-8")


def _write_card_ass(ep: dict, shot, dest: Path) -> None:
    """Build a readable, non-narrated choice/ending card from actual story keys."""
    if shot.kind not in {"vote", "ending"}:
        raise VisualContractError("visual cards are reserved for vote/ending nodes")
    if not ep.get("choices"):
        raise VisualContractError("vote/ending card has no real story choices")
    rows = []
    for n, choice in enumerate(ep["choices"], 1):
        label = str(choice.get("text") or choice.get("key") or "").strip()
        if not label:
            raise VisualContractError(f"empty choice label on {shot.kind} card")
        rows.append(f"{n} — {label}")
    if len(rows) > 3:
        raise VisualContractError("choice card cannot show more than three readable options")
    header = "YOU DECIDE" if shot.kind == "vote" else "CHOOSE THE NEXT CHAPTER"
    footer = "COMMENT 1 OR 2" if len(rows) == 2 else "COMMENT YOUR CHOICE"
    message = r"\N\N".join([
        _ass_escape(header),
        *[_ass_escape(row) for row in rows],
        _ass_escape(footer),
    ])
    seconds = max(0.1, float(shot.dur))
    ass = (
        "[Script Info]\nScriptType: v4.00+\nPlayResX: 1080\n"
        "PlayResY: 1920\nWrapStyle: 2\nScaledBorderAndShadow: yes\n\n"
        "[V4+ Styles]\nFormat: Name, Fontname, Fontsize, PrimaryColour, "
        "SecondaryColour, OutlineColour, BackColour, Bold, Italic, "
        "Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, "
        "BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding\n"
        "Style: CHOICE,DejaVu Sans,55,&H00FFFFFF,&H00FFFFFF,"
        "&H80000000,&HA0000000,-1,0,0,0,100,100,0,0,"
        "1,3,1,5,70,70,75,1\n\n"
        "[Events]\nFormat: Layer, Start, End, Style, Name, MarginL, "
        "MarginR, MarginV, Effect, Text\n"
        f"Dialogue: 0,{_ass_clock(0)},{_ass_clock(seconds)},"
        f"CHOICE,,0,0,0,,{message}\n"
    )
    dest.write_text(ass, encoding="utf-8")


def _render_choice_card(ep: dict, shot, dest: Path, work: Path,
                        fps: int, crf: int) -> None:
    """Purpose-built text card; never passed off as physical story footage."""
    if shot.dur <= 0:
        raise VisualContractError("choice card duration must be positive")
    ass = work / (dest.stem + ".ass")
    _write_card_ass(ep, shot, ass)
    run([
        "ffmpeg", "-hide_banner", "-loglevel", "error", "-y",
        "-f", "lavfi", "-i",
        f"color=c=0x0d141f:s=1080x1920:r={fps}:d={float(shot.dur):.3f}",
        "-vf", f"ass={ass.as_posix()}",
        "-t", f"{float(shot.dur):.3f}", "-an",
        "-c:v", "libx264", "-preset", "medium", "-crf", str(crf),
        "-pix_fmt", "yuv420p", str(dest),
    ])


def render_cinematic_episode(cfg: dict, ep: dict, voices: list, shots: list,
                             total: float, audio: Path, work: Path,
                             out_path: Path, crf: int = 18, Log=print) -> dict:
    manifest = build_manifest(ep, allow_unimplemented=True)
    sources = validate_assets(ep, shots)
    # Approval is bound to exact MP4 and shot-prompt SHA-256 digests, not a
    # mutable reviewed=true flag that could survive changed footage.
    from cinematic_review import verify_manifest
    verdict = verify_manifest(manifest)
    manifest["approval"]["approved"] = verdict["approved"]
    manifest["approval"]["reviewed_by"] = verdict["reviewed_by"]
    for frame in manifest["shots"]:
        frame["reviewed"] = True
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "visual_manifest.json").write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    fps = int(cfg.get("render", {}).get("fps", 30))
    segments_dir = work / "cinematic_segments"
    segments_dir.mkdir(parents=True, exist_ok=True)
    segments = []
    source_iter = iter(sources)
    for index, shot in enumerate(shots):
        segment = segments_dir / f"{index:03d}.mp4"
        target_duration = float(shot.dur)
        if shot.kind in {"vote", "ending"}:
            # These are explicitly graphical, non-narrated end screens,
            # not generic generated footage covering spoken physical actions.
            Log(f"[cinematic] {shot.kind} graphic card {index}: {target_duration:.2f}s")
            _render_choice_card(ep, shot, segment, work, fps, crf)
        else:
            selected_shot, source = next(source_iter)
            if selected_shot is not shot:
                raise VisualContractError("narrated shot/source ordering changed")
            Log(f"[cinematic] {shot.kind} {index}: {source.name} {target_duration:.2f}s")
            run([
                "ffmpeg", "-hide_banner", "-loglevel", "error", "-y",
                "-i", str(source), "-t", f"{target_duration:.3f}",
                "-vf", f"scale=1080:1920:force_original_aspect_ratio=increase,"
                       f"crop=1080:1920,fps={fps},setsar=1",
                "-an", "-c:v", "libx264", "-preset", "medium",
                "-crf", str(crf), "-pix_fmt", "yuv420p",
                str(segment),
            ])
        segments.append(segment)
    concat_file = segments_dir / "concat.txt"
    concat_file.write_text(
        "".join(f"file '{p.as_posix()}'\n" for p in segments),
        encoding="utf-8"
    )
    subtitles = work / "captions.ass"
    build_subtitles(shots, voices, subtitles)
    run([
        "ffmpeg", "-hide_banner", "-loglevel", "error", "-y",
        "-f", "concat", "-safe", "0", "-i", str(concat_file),
        "-i", str(audio), "-vf",
        f"eq=contrast=1.065:saturation=1.12:brightness=0.008,"
        f"colorbalance=bs=0.022:gs=0.006:rs=0.006,ass={subtitles.name}",
        "-c:v", "libx264", "-preset", "medium", "-crf", str(crf),
        "-pix_fmt", "yuv420p", "-c:a", "aac", "-b:a", "160k",
        "-movflags", "+faststart", "-shortest", str(out_path),
    ], cwd=work)
    probe = _probe_video(out_path)
    if abs(probe["duration"] - total) > 1.1:
        raise VisualContractError(
            f"cinematic video timeline mismatch: final {probe['duration']:.2f}s; "
            f"expected {total:.2f}s"
        )
    ep["visual_mode_used"] = "cinematic_assets"
    return {
        "video_path": str(out_path), "duration": probe["duration"],
        "shots": len(shots), "render_seconds": None,
        "cinematic_manifest": str(OUT_DIR / "visual_manifest.json")
    }
